import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';

const capability = JSON.parse(
  await readFile('apps/desktop/src-tauri/capabilities/foundation.json', 'utf8'),
);
const tauriConfig = JSON.parse(await readFile('apps/desktop/src-tauri/tauri.conf.json', 'utf8'));
const cargoManifest = await readFile('apps/desktop/src-tauri/Cargo.toml', 'utf8');
const rustBuild = await readFile('apps/desktop/src-tauri/build.rs', 'utf8');
const rustMain = await readFile('apps/desktop/src-tauri/src/main.rs', 'utf8');
const nativeFiles = await readFile('apps/desktop/src-tauri/src/native_files.rs', 'utf8');
const secureSession = await readFile('apps/desktop/src-tauri/src/secure_session.rs', 'utf8');
const updates = await readFile('apps/desktop/src-tauri/src/updates.rs', 'utf8');
const developerProfile = await readFile('apps/desktop/src-tauri/src/developer_profile.rs', 'utf8');
assert.match(developerProfile, /const PROFILE_URL: &str = "https:\/\/github\.com\/kevindemara"/u);
assert.match(developerProfile, /pub fn open_developer_profile\(\)/u);
assert.match(
  developerProfile,
  /ShellExecuteW\(null_mut\(\), verb\.as_ptr\(\), url\.as_ptr\(\), null\(\), null\(\), 1\)/u,
);
assert.doesNotMatch(developerProfile, /(?:std::process|Command::|runas|println!|eprintln!|dbg!)/u);

const nativeFileCommands = [
  'choose_pdf',
  'read_pdf_chunk',
  'cancel_pdf_read',
  'take_launch_pdf',
  'get_recent_files',
  'set_recent_files_enabled',
  'clear_recent_files',
  'open_recent_pdf',
  'choose_save_pdf',
  'write_pdf_chunk',
  'cancel_pdf_write',
];
const secureSessionCommands = [
  'store_secure_session',
  'get_secure_session',
  'clear_secure_session',
  'store_secure_entitlement',
  'get_secure_entitlement',
  'clear_secure_entitlement',
];
const updateCommands = ['check_for_update', 'install_available_update'];
const reviewedCommands = [
  ...nativeFileCommands,
  ...secureSessionCommands,
  ...updateCommands,
  'open_developer_profile',
];
const reviewedPermissions = reviewedCommands.map(
  (command) => `allow-${command.replaceAll('_', '-')}`,
);
const capabilityPermissions = [
  ...reviewedPermissions,
  'core:event:allow-listen',
  'core:event:allow-unlisten',
];
const generatedPermissions = await Promise.all(
  reviewedCommands.map((command) =>
    readFile(`apps/desktop/src-tauri/permissions/autogenerated/${command}.toml`, 'utf8'),
  ),
);

assert.deepEqual(
  capability.permissions,
  capabilityPermissions,
  'The Windows alpha may grant only the reviewed file, session, update and fixed-profile commands.',
);
assert.deepEqual(
  capability.platforms,
  ['windows'],
  'The native file capability must remain Windows-only.',
);
assert.equal(capability.remote, undefined, 'Remote origins must never receive native file access.');
assert.deepEqual(
  tauriConfig.app.security.capabilities,
  ['foundation'],
  'Only the reviewed Windows capability may be active.',
);
assert.equal(tauriConfig.bundle.active, false, 'Unsigned installer bundling must remain disabled.');
assert.deepEqual(
  tauriConfig.bundle.fileAssociations,
  [
    {
      description: 'PDF document',
      ext: ['pdf'],
      mimeType: 'application/pdf',
      name: 'PDF document',
      role: 'Editor',
    },
  ],
  'The installer may associate only PDF documents.',
);
assert.equal(
  tauriConfig.app.windows[0].url,
  undefined,
  'The privileged window must load only bundled application code.',
);
assert.equal(
  tauriConfig.app.windows[0].dragDropEnabled,
  false,
  'HTML file drops must stay in the shared renderer without exposing native paths.',
);
assert.match(
  tauriConfig.app.security.csp,
  /default-src 'self'/u,
  'The desktop CSP must keep bundled code as the default source.',
);
assert.doesNotMatch(
  tauriConfig.app.security.csp,
  /https:(?:[;\s]|$)|http:\/\/(?!ipc\.localhost|127\.0\.0\.1:(?:3000|55321)|localhost:(?:3000|55321))/u,
  'The desktop CSP must not permit arbitrary remote or non-loopback HTTP connections.',
);
assert.match(
  nativeFiles,
  /MAXIMUM_COMMENT_REPORT_BYTES: u64 = 3 \* 1024 \* 1024/u,
  'Native comment reports must retain their dedicated three-megabyte limit.',
);
assert.match(
  nativeFiles,
  /"application\/json" => Ok\(Self::CommentReport\)/u,
  'Native JSON saving must stay restricted to the reviewed comment-report kind.',
);
assert.match(
  nativeFiles,
  /transport_type != "application\/octet-stream" \|\| document_type != kind\.mime_type\(\)/u,
  'Binary transport and selected document MIME must both be validated, not conflated.',
);
assert.match(
  nativeFiles,
  /request_header\(&request, "x-pdfmason-content-type"\)/u,
  'Document MIME must survive the Tauri transport Content-Type override.',
);
assert.match(
  nativeFiles,
  /validate_save_content_types\(transfer\.kind, transport_type, document_type\)\?;/u,
  'The active save handler must invoke the independent MIME checks.',
);
assert.match(
  tauriConfig.app.security.csp,
  /https:\/\/\*\.supabase\.co/u,
  'Production authentication may connect only to the configured Supabase vendor domain class.',
);

const appManifestMatch = /\.commands\(&\[([\s\S]*?)\]\)/u.exec(rustBuild);
assert.notEqual(appManifestMatch, null, 'Custom commands must be registered in AppManifest ACL.');
const manifestCommands = [...(appManifestMatch?.[1] ?? '').matchAll(/"([a-z_]+)"/gu)].map(
  (match) => match[1],
);
assert.deepEqual(manifestCommands, reviewedCommands, 'AppManifest command ACL drifted.');

const handlerMatch = /generate_handler!\[([\s\S]*?)\]/u.exec(rustMain);
assert.notEqual(handlerMatch, null, 'The reviewed commands must have one invoke handler.');
const handlerCommands = [
  ...(handlerMatch?.[1] ?? '').matchAll(
    /(?:native_files|secure_session|updates|developer_profile)::([a-z_]+)/gu,
  ),
].map((match) => match[1]);
assert.deepEqual(handlerCommands, reviewedCommands, 'Runtime command registration drifted.');

for (const [index, permission] of generatedPermissions.entries()) {
  const command = reviewedCommands[index];
  assert.notEqual(command, undefined);
  assert.deepEqual(
    [...permission.matchAll(/commands\.allow = \["([a-z_]+)"\]/gu)].map((match) => match[1]),
    [command],
    `Generated allow permission drifted for ${command}.`,
  );
  assert.deepEqual(
    [...permission.matchAll(/commands\.deny = \["([a-z_]+)"\]/gu)].map((match) => match[1]),
    [command],
    `Generated deny permission drifted for ${command}.`,
  );
}

assert.match(rustMain, /\.plugin\(tauri_plugin_dialog::init\(\)\)/u);
assert.doesNotMatch(
  capability.permissions.join('\n'),
  /(?:dialog|fs|http|shell):/u,
  'The frontend must not receive direct plugin filesystem, dialog, HTTP, or shell commands.',
);
assert.doesNotMatch(
  cargoManifest,
  /tauri-plugin-(?:fs|http|shell|process)/u,
  'No broad filesystem, HTTP, or shell plugin may be linked.',
);
assert.doesNotMatch(
  capability.permissions.join('\n'),
  /updater:/u,
  'The renderer must use the reviewed update wrapper, not broad updater plugin commands.',
);
assert.doesNotMatch(
  nativeFiles,
  /(?:println!|eprintln!|dbg!)/u,
  'Native file commands must not log paths or bytes.',
);
assert.doesNotMatch(
  secureSession,
  /(?:println!|eprintln!|dbg!)/u,
  'Secure session commands must not log credentials or decrypted values.',
);
assert.match(
  secureSession,
  /CryptProtectData/u,
  'Desktop sessions must use Windows user-scoped DPAPI protection.',
);
for (const code of nativeFileCommands)
  assert.match(nativeFiles, new RegExp(`pub (?:async )?fn ${code}\\b`, 'u'));
for (const code of secureSessionCommands)
  assert.match(secureSession, new RegExp(`pub (?:async )?fn ${code}\\b`, 'u'));
for (const code of updateCommands)
  assert.match(updates, new RegExp(`pub (?:async )?fn ${code}\\b`, 'u'));
assert.match(
  updates,
  /download_and_install/u,
  'The reviewed update wrapper must retain Tauri signature verification before install.',
);
assert.doesNotMatch(
  updates,
  /(?:println!|eprintln!|dbg!)/u,
  'Update checks must not log endpoints, release payloads, or installer details.',
);

process.stdout.write(
  'Tauri Windows alpha surface is allowlisted: bounded PDF/comment-report/recent/launch, DPAPI session, update and fixed developer-profile commands plus content-free event listening; no arbitrary URL or remote/plugin filesystem access.\n',
);
