// Optional deterministic asset regeneration. Never reads user-selected fonts/PDFs.
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const wheel = path.resolve(process.argv[2] ?? '');
assert.match(path.basename(wheel), /^fonttools-4\.67\.0-py3-none-any\.whl$/u);
const source = await readFile(
  path.join(root, 'packages/pdf-engine/src/signature-font-data.ts'),
  'utf8',
);
const encoded = source.match(/export const signatureFontBase64\s*=\s*'([A-Za-z0-9+/=]+)'/u)?.[1];
assert.ok(encoded);
const bytes = Buffer.from(encoded, 'base64');
assert.equal(bytes.length, 133636);
assert.equal(
  createHash('sha256').update(bytes).digest('hex'),
  '21808625578fe8d8cd10cb684be546dca077b27cd03a53a2f1ec11dc743c924c',
);
const output = execFileSync(
  process.env.PDFMASON_PYTHON_PATH ?? 'python',
  [path.join(root, 'scripts/signature-font-facts.py'), wheel],
  { input: bytes, maxBuffer: 4 * 1024 * 1024, timeout: 30000, windowsHide: true },
);
const facts = JSON.parse(output.toString('utf8'));
assert.equal(facts.characters.length, 559);
assert.equal(
  facts.sourceFontSha256,
  '21808625578fe8d8cd10cb684be546dca077b27cd03a53a2f1ec11dc743c924c',
);
const generated =
  '// Copyright 2016 The Dancing Script Project Authors. Derived outline/metric data: SIL OFL-1.1.\n' +
  '// PDFrig Script Preview; see docs/dependencies/DancingScript-OFL.txt and signature-font-review.json.\n' +
  '// Generated by scripts/generate-signature-font-facts.mjs; do not edit numeric data by hand.\n' +
  "import type { SignatureFontFacts } from './fixed-signature-font.js';\n" +
  '// prettier-ignore\nexport const signatureFontFacts: SignatureFontFacts = ' +
  JSON.stringify(facts) +
  ';\n';
const destination = path.join(root, 'packages/pdf-engine/src/signature-font-facts.ts');
if (process.argv.includes('--write')) await writeFile(destination, generated);
else if (process.argv.includes('--candidate'))
  await writeFile(
    path.join(root, 'tmp/signature-font-facts-candidate.json'),
    JSON.stringify(facts),
  );
else assert.equal(await readFile(destination, 'utf8'), generated);
console.log(
  JSON.stringify({
    characters: facts.characters.length,
    glyphs: facts.glyphs.length,
    generatedSha256: createHash('sha256').update(generated).digest('hex'),
    bytes: Buffer.byteLength(generated),
  }),
);
